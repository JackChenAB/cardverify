const saved = localStorage.getItem('keyline-locale');
const locale = ref<Locale>(saved === 'en' || saved === 'zh-TW' ? saved : 'zh-TW');

function translate(key: MessageKey, values: Record<string, string | number> = {}): string {
  let message = (locale.value === 'en' ? en : zhTW)[key];
  for (const [name, value] of Object.entries(values)) {
    message = message.replaceAll(`{${name}}`, String(value));
  }
  return message;
}

function setLocale(next: Locale) {
  locale.value = next;
}

watch(
  locale,
  (next) => {
    localStorage.setItem('keyline-locale', next);
    document.documentElement.lang = next;
    document.title = (next === 'en' ? en : zhTW)['app.title'];
  },
  { immediate: true },
);

export function useI18n() {
  return {
    locale,
    isEnglish: computed(() => locale.value === 'en'),
    setLocale,
    toggleLocale: () => setLocale(locale.value === 'en' ? 'zh-TW' : 'en'),
    t: translate,
  };
}
